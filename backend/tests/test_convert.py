# ---------------------------------------------------------------------------
# Geometry helpers for ground-truth assertions (independent of vertex ordering)
# ---------------------------------------------------------------------------

def polygon_matches(polygon, expected_corners, tol: float = 0.05) -> bool:
    """True if every polygon vertex is near an expected corner and vice versa."""
    def covered(points, targets):
        return all(
            any(math.dist(p, t) <= tol for t in targets) for p in points
        )
    return covered(polygon, expected_corners) and covered(expected_corners, polygon)


def opening_span(model: HomeModel, opening: Opening):
    """World-space endpoints of an opening from its parametric wall_segment."""
    floor = model.floors[0]
    room = next(r for r in floor.rooms if r.id == opening.wall_segment.room_id)
    n = len(room.polygon)
    a = room.polygon[opening.wall_segment.edge_index]
    b = room.polygon[(opening.wall_segment.edge_index + 1) % n]
    def lerp(t):
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    return lerp(opening.wall_segment.t0), lerp(opening.wall_segment.t1)


def opening_center(model: HomeModel, opening: Opening):
    p, q = opening_span(model, opening)
    return ((p[0] + q[0]) / 2.0, (p[1] + q[1]) / 2.0)


def find_opening(model: HomeModel, kind: str, room_ids: set[str]) -> Opening:
    for op in model.floors[0].openings:
        if op.kind.value == kind and set(op.room_ids) == room_ids:
            return op
    raise AssertionError(f"no {kind} opening with room_ids {room_ids}")


