@pytest.mark.parametrize("name", SCAN_NAMES)
def test_output_validates_against_schema_and_pydantic(name):
    model = convert(name)
    document = json.loads(model.model_dump_json(exclude_none=True))
    schema = json.loads(SCHEMA_PATH.read_text())
    jsonschema.validate(document, schema)  # shape
    HomeModel.model_validate(document)  # geometry + cross-refs round-trip


@pytest.mark.parametrize("name", SCAN_NAMES)
def test_conversion_is_idempotent(name):
    first = convert(name).model_dump_json(exclude_none=True)
    second = convert(name).model_dump_json(exclude_none=True)
    assert first == second
    # Pre-parsed input takes the same path.
    via_structure = convert_scan(
        RPStructure.parse(load_scan(name)), home_name=name, timestamp=TS
    ).model_dump_json(exclude_none=True)
    assert via_structure == first


@pytest.mark.parametrize("name", SCAN_NAMES)
def test_all_scan_items_carry_confidence(name):
    model = convert(name)
    for floor in model.floors:
        for item in [*floor.rooms, *floor.openings]:
            assert item.source.value == "scan"
            assert item.confidence is not None


# ---------------------------------------------------------------------------
# Fixture 1: clean rectangular bungalow (identifier-matched shared door)
# ---------------------------------------------------------------------------

class TestBungalow:
    @pytest.fixture(scope="class")
    def model(self) -> HomeModel:
        return convert("synthetic-bungalow.roomplan.json")

    def test_rooms_recover_ground_truth_footprints(self, model):
        floor = model.floors[0]
        assert len(floor.rooms) == 2
        living = next(r for r in floor.rooms if r.type.value == "living")
        bedroom = next(r for r in floor.rooms if r.type.value == "bedroom")
        assert polygon_matches(living.polygon, [(0, 0), (5, 0), (5, 4), (0, 4)])
        assert polygon_matches(bedroom.polygon, [(0, 4), (5, 4), (5, 8), (0, 8)])
        assert living.name == "Living Room"
        for room in floor.rooms:
            assert room.confidence >= 0.8  # clean high-confidence scan

    def test_exterior_door_and_windows_mapped(self, model):
        floor = model.floors[0]
        living = next(r for r in floor.rooms if r.type.value == "living")
        front = find_opening(model, "door", {living.id, EXTERIOR_ID})
        cx, cy = opening_center(model, front)
        assert math.dist((cx, cy), (1.45, 0.0)) < 0.05  # planted at x 1.0-1.9, y=0
        p, q = opening_span(model, front)
        assert abs(math.dist(p, q) - 0.9) < 0.05

        exterior_windows = [
            op for op in floor.openings
            if op.kind.value == "window" and EXTERIOR_ID in op.room_ids
        ]
        assert len(exterior_windows) == 2
        for w in exterior_windows:
            assert w.sill_height_m == pytest.approx(0.8, abs=0.02)
            assert w.height_m == pytest.approx(1.2, abs=0.02)

    def test_shared_door_becomes_two_room_adjacency(self, model):
        floor = model.floors[0]
        living = next(r for r in floor.rooms if r.type.value == "living")
        bedroom = next(r for r in floor.rooms if r.type.value == "bedroom")
        shared = find_opening(model, "door", {living.id, bedroom.id})
        cx, cy = opening_center(model, shared)
        assert math.dist((cx, cy), (2.45, 4.0)) < 0.05  # planted at x 2.0-2.9, y=4
        # The same surface appears in both rooms' doors arrays; it must come out
        # as ONE opening, not two.
        doors = [op for op in floor.openings if op.kind.value == "door"]
        assert len(doors) == 2  # front + shared


# ---------------------------------------------------------------------------
# Fixture 2: messy scan (gap, near-collinear split wall, 3° rotation, drift)
# ---------------------------------------------------------------------------

class TestMessy:
    @pytest.fixture(scope="class")
    def model(self) -> HomeModel:
        return convert("synthetic-messy.roomplan.json")

    def test_produces_valid_single_room_without_crashing(self, model):
        floor = model.floors[0]
        assert len(floor.rooms) == 1
        polygon = list(floor.rooms[0].polygon)
        assert is_simple_polygon(polygon)
        assert signed_area(polygon) > 0

    def test_split_wall_merged_and_gap_closed(self, model):
        room = model.floors[0].rooms[0]
        # 5 wall surfaces (one split, one short) must still collapse to a quad.
        assert len(room.polygon) == 4
        area = signed_area(list(room.polygon))
        assert area == pytest.approx(12.0, rel=0.1)  # nominal 4 m x 3 m

    def test_low_confidence_flags_instead_of_drops(self, model):
        floor = model.floors[0]
        room = floor.rooms[0]
        assert room.confidence < 0.5  # gap penalty + mediocre wall confidence

        # The drifting door (0.6 m off every wall) is kept, demoted, not dropped.
        doors = [op for op in floor.openings if op.kind.value == "door"]
        assert len(doors) == 1
        assert doors[0].confidence <= 0.25
        assert EXTERIOR_ID in doors[0].room_ids

        windows = [op for op in floor.openings if op.kind.value == "window"]
        assert len(windows) == 1
        assert windows[0].confidence <= 0.3  # RoomPlan "low" carried through


# ---------------------------------------------------------------------------
# Fixture 3: shared door via geometric matching (different identifiers)
# ---------------------------------------------------------------------------

class TestSharedDoorGeometric:
    @pytest.fixture(scope="class")
    def model(self) -> HomeModel:
        return convert("synthetic-shared-door.roomplan.json")

    def test_geometrically_coincident_doors_pair_into_adjacency(self, model):
        floor = model.floors[0]
        kitchen = next(r for r in floor.rooms if r.type.value == "kitchen")
        hall = next(r for r in floor.rooms if r.type.value == "hall")
        shared = find_opening(model, "door", {kitchen.id, hall.id})
        cx, _ = opening_center(model, shared)
        assert cx == pytest.approx(4.0, abs=0.1)

    def test_unshared_surfaces_go_to_exterior(self, model):
        floor = model.floors[0]
        hall = next(r for r in floor.rooms if r.type.value == "hall")
        kitchen = next(r for r in floor.rooms if r.type.value == "kitchen")
        back = find_opening(model, "door", {hall.id, EXTERIOR_ID})
        assert opening_center(model, back)[0] == pytest.approx(8.0, abs=0.05)
        find_opening(model, "window", {kitchen.id, EXTERIOR_ID})
        # 4 raw door/window surfaces pair down to exactly 3 openings.
        assert len(floor.openings) == 3


