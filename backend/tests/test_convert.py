class TestSharedDoorGeometric:
    @pytest.fixture
    def model(self) -> HomeModel:
        return convert("synthetic-shared-door.roomplan.json")

    def test_geometrically_coincident_doors_pair_into_adjacency(self, model):
        floor = model.floors[0]
        kitchen = next(r for r in floor.rooms if r.type.value == "kitchen")
        hall = next(r for r in floor.rooms if r.type.value == "hall")
        shared = find_opening(model, "door", {kitchen.id, hall.id})
        cx, _ = opening_center(model, shared)
        assert cx == pytest.approx(4.0, abs=0.1)

    def test_unshared_surfaces_go_to_exterior(self, model):
        floor = model.floors[0]
        hall = next(r for r in floor.rooms if r.type.value == "hall")
        kitchen = next(r for r in floor.rooms if r.type.value == "kitchen")
        back = find_opening(model, "door", {hall.id, EXTERIOR_ID})
        assert opening_center(model, back)[0] == pytest.approx(8.0, abs=0.05)
        find_opening(model, "window", {kitchen.id, EXTERIOR_ID})
        # 4 raw door/window surfaces pair down to exactly 3 openings.
        assert len(floor.openings) == 3

    def test_objects_kitchen_appliances_mapped(self, model):
        floor = model.floors[0]
        # shared_door has stove and fridge
        assert len(floor.objects) == 2
        cats = {obj.category.value for obj in floor.objects}
        assert cats == {"heat_source", "appliance"}


