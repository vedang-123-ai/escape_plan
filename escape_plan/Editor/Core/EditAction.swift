//  EditAction.swift — the complete vocabulary of editor mutations.
//
//  Every change to a HomeModel is one of these values, dispatched to HomeModelStore. Nothing
//  else may mutate the model (rules/languages/swift.md). Because the set is closed and each
//  action is a plain value, undo/redo (S2.2) and autosave are bookkeeping on top of it rather
//  than a rewrite.
//
//  Note what is deliberately ABSENT: nothing here touches `egress` (computed by the S1.1
//  backend annotator) or the geometry of an opening relative to its wall (parametric refs mean
//  openings ride along when walls move — that is the schema design paying off, not an action).

import Foundation

enum EditAction: Equatable, Sendable {

    // MARK: Home
    case setHomeName(String)

    // MARK: Floors
    /// Inserts a floor directly above or below `relativeTo`, taking the next free level.
    /// The new floor is seeded with one default room, because the schema requires every floor
    /// to have at least one (see `HomeModelStore.defaultRoomSize`).
    case addFloor(relativeTo: String, above: Bool)
    case deleteFloor(floorId: String)
    case renameFloor(floorId: String, name: String)
    case setFloorHeight(floorId: String, height_m: Double)

    // MARK: Rooms
    case addRoom(floorId: String, origin: Point, width_m: Double, height_m: Double,
                 type: RoomType, name: String)
    /// Cascades to the room's openings. Rejected if a profile or stair still references it.
    case deleteRoom(roomId: String)
    case renameRoom(roomId: String, name: String)
    case setRoomType(roomId: String, type: RoomType)

    // MARK: Drags
    /// Moves one corner. Connected walls follow because they share the vertex.
    case dragVertex(roomId: String, vertexIndex: Int, to: Point)
    /// Translates wall `edgeIndex` by `by`; the two neighbouring walls stretch to keep up.
    case dragEdge(roomId: String, edgeIndex: Int, by: Point)
    /// Translates the whole footprint.
    case dragRoom(roomId: String, by: Point)
    /// Slides an opening along its host wall. `t` is the normalized position of the opening's
    /// MIDPOINT on its wall edge, in [0,1]; the reducer derives t0/t1 from `t` and the opening's
    /// existing width_m, so the caller never computes wall-length itself.
    case dragOpening(openingId: String, t: Double)

    // MARK: Openings
    /// Places a door/window on wall `edgeIndex` of `roomId`, centered as close to `t` (the
    /// tap's normalized position on that edge) as the wall allows. Width/height/sill come from
    /// `OpeningPlacement.defaults(for:)`; `room_ids` is DERIVED — another room sharing that
    /// stretch of wall makes it an interior opening, otherwise it faces EXTERIOR (a door there
    /// is an exit). The user is never asked interior-vs-exterior.
    case addOpening(roomId: String, edgeIndex: Int, t: Double, kind: OpeningKind)
    case deleteOpening(openingId: String)
    /// Door <-> window. Height and sill jump to the new kind's defaults (a door's 0-sill makes
    /// no sense on a window and vice versa); width and position stay put.
    case setOpeningKind(openingId: String, kind: OpeningKind)
    /// Re-centers the existing span around its midpoint at the new width.
    case setOpeningWidth(openingId: String, width_m: Double)

    // MARK: Objects (schema v1.1 — revamp B2)
    /// Places a box-primitive object at `center` on `floorId`. `objectId` is generated by the
    /// caller (UUID) so the action stays a plain value.
    case addObject(objectId: String, floorId: String, category: ObjectCategory, center: Point,
                   size_m: [Double], height_m: Double)
    case deleteObject(objectId: String)
    /// Translates the object's center.
    case dragObject(objectId: String, by: Point)
    case rotateObject(objectId: String, rotation_deg: Double)
    case resizeObject(objectId: String, size_m: [Double], height_m: Double)
    case setObjectCategory(objectId: String, category: ObjectCategory)
    case setObjectSecured(objectId: String, secured: Bool)
    case setObjectMounted(objectId: String, mounted: Bool)
    case setObjectElevation(objectId: String, elevation_m: Double)

    // MARK: Stairs (S2.2)
    /// Connects `fromRoomId` on `fromFloorId` to `toRoomId` on another floor. `footprint` is a
    /// simple polygon in the FROM floor's local coordinates (the renderer/model draw stairs on
    /// `from.floor_id`'s plane — see DollhouseScene.makeStairs).
    case addStairs(fromFloorId: String, fromRoomId: String, toFloorId: String, toRoomId: String,
                    footprint: Polygon, kind: StairKind)
    case deleteStairs(stairsId: String)

    // MARK: AI-draft review (revamp C2)
    /// The user has reviewed the AI-drafted home: every element with source `ai_plan` flips
    /// to `manual` in one commit (undoable). This is the gate-opener — routes are never
    /// fetched while any ai_plan element remains.
    case confirmAIDraft

    // MARK: Profiles (S3.4)
    /// `profileId` is generated by the caller (UUID) so the action stays a plain value.
    case addProfile(profileId: String, name: String, tags: [ProfileTag], bedroom_room_id: String)
    case updateProfile(profileId: String, name: String, tags: [ProfileTag], bedroom_room_id: String)
    case deleteProfile(profileId: String)
    case setHousehold(tenure: Tenure?, existingEquipment: [Equipment])
}

extension EditAction {
    /// Human-readable label — S2.2 uses this for "Undo Move Wall" style menu titles.
    var undoLabel: String {
        switch self {
        case .setHomeName: return "Rename Home"
        case .addFloor: return "Add Floor"
        case .deleteFloor: return "Delete Floor"
        case .renameFloor: return "Rename Floor"
        case .setFloorHeight: return "Change Ceiling Height"
        case .addRoom: return "Add Room"
        case .deleteRoom: return "Delete Room"
        case .renameRoom: return "Rename Room"
        case .setRoomType: return "Change Room Type"
        case .dragVertex: return "Move Corner"
        case .dragEdge: return "Move Wall"
        case .dragRoom: return "Move Room"
        case .dragOpening: return "Move Opening"
        case .addOpening(_, _, _, let kind):
            return kind == .door ? "Add Door" : "Add Window"
        case .deleteOpening: return "Delete Opening"
        case .setOpeningKind: return "Change Opening Type"
        case .setOpeningWidth: return "Resize Opening"
        case .addObject: return "Add Object"
        case .deleteObject: return "Delete Object"
        case .dragObject: return "Move Object"
        case .rotateObject: return "Rotate Object"
        case .resizeObject: return "Resize Object"
        case .setObjectCategory: return "Change Object Type"
        case .setObjectSecured: return "Toggle Object Secured"
        case .setObjectMounted: return "Toggle Object Mounted"
        case .setObjectElevation: return "Change Object Elevation"
        case .addStairs: return "Add Stairs"
        case .deleteStairs: return "Delete Stairs"
        case .confirmAIDraft: return "Confirm AI Draft"
        case .addProfile: return "Add Profile"
        case .updateProfile: return "Edit Profile"
        case .deleteProfile: return "Delete Profile"
        case .setHousehold: return "Edit Household"
        }
    }

    /// True for the continuous gestures. S2.2 coalesces a drag's many intermediate actions into
    /// one undo entry instead of 200.
    var isContinuousDrag: Bool {
        switch self {
        case .dragVertex, .dragEdge, .dragRoom, .dragOpening, .dragObject: return true
        default: return false
        }
    }
}

// MARK: - Selection

/// What the user currently has selected. NOT part of the HomeModel — it is editor UI state and
/// must never be persisted into the document.
enum Selection: Equatable, Sendable {
    case none
    case room(roomId: String)
    case wall(roomId: String, edgeIndex: Int)
    case vertex(roomId: String, vertexIndex: Int)
    case opening(openingId: String)
    case stairs(stairsId: String)
    case object(objectId: String)

    var roomId: String? {
        switch self {
        case .none, .opening, .stairs, .object: return nil
        case .room(let id), .wall(let id, _), .vertex(let id, _): return id
        }
    }
}
